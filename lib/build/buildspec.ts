/**
 * Buildspec generation for the CodeBuild executor.
 *
 * This mirrors, step for step, what the local executor does in
 * lib/build/pipeline.ts:
 *
 *   detect Next.js → force `output: "standalone"` (cjs/mjs wrap) →
 *   install deps (npm ci / pnpm / yarn) → next build → assemble the
 *   standalone tree + run.sh → zip → upload to the project bucket
 *
 * Two modes come out of the container:
 *   ssr    → s3://<bucket>/versions/<commit>.zip (Lambda package)
 *   static → s3://<bucket>/static/**          (CDN files)
 *
 * The runner recovers the mode / commit metadata by parsing the
 * `[openhost] KEY=value` marker lines echoed here (also relayed to SSE).
 */

interface BuildspecOpts {
  bucket: string;
}

/**
 * Indentation contract for the generated YAML:
 * `phases:` at 0, phase keys at 2, `commands:` at 4, `- |` at 6 and every
 * script line at 8 — the block scalar strips exactly 8, so heredoc bodies
 * and terminators land at column 0 of the shell script.
 */
const S = ' '; // keeps line templates readable below

export function generateOpenHostBuildspec(opts: BuildspecOpts): string {
  void opts; // bucket + region arrive as StartBuild env overrides (BUCKET / AWS_DEFAULT_REGION)

  return [
    'version: 0.2',
    'run-as: root',
    'phases:',
    '  install:',
    '    commands:',
    '      - |',
    i(`set -euo pipefail`),
    i(`echo "[openhost] Build sandbox up: $(uname -m), node $(node -v)"`),
    i(`# Ensure Node >= 20 (Lambda-runtime images ship it; older ones get nvm).`),
    i(`if ! node -e "process.exit(Number(process.versions.node.split('.')[0]) >= 20 ? 0 : 1)"; then`),
    i(`  git clone -q https://github.com/nvm-sh/nvm.git /root/.nvm`),
    i(`  . /root/.nvm/nvm.sh`),
    i(`  nvm install 20 >/dev/null`),
    i(`  nvm alias default 20 >/dev/null`),
    i(`  nvm use 20 >/dev/null`),
    i(`fi`),
    i(`echo "[openhost] Node $(node -v) / npm $(npm -v)"`),
    i(`# Amazon-Linux-based images may lack zip / the AWS CLI — best-effort installs.`),
    i(`command -v zip >/dev/null 2>&1 || { dnf install -y -q zip 2>/dev/null || yum install -y -q zip 2>/dev/null || apt-get install -y -q zip; }`),
    i(`if ! command -v aws >/dev/null 2>&1; then`),
    i(`  (dnf install -y -q awscli2 2>/dev/null || yum install -y -q awscli2 2>/dev/null) || {`),
    i(`    (dnf install -y -q unzip 2>/dev/null || yum install -y -q unzip 2>/dev/null || apt-get install -y -q unzip) && curl -fsSL "https://awscli.amazonaws.com/awscli-exe-linux-x86_64.zip" -o /tmp/awscliv2.zip && (cd /tmp && unzip -q awscliv2.zip && ./aws/install >/dev/null 2>&1);`),
    i(`  }`),
    i(`fi`),
    i(`echo "[openhost] tools: zip=$(command -v zip >/dev/null && echo ok || echo missing), aws=$(aws --version 2>/dev/null || echo missing)"`),
    '',
    '  pre_build:',
    '    commands:',
    '      - |',
    i(`set -euo pipefail`),
    i(`cd "$CODEBUILD_SRC_DIR"`),
    i(`[ -s /root/.nvm/nvm.sh ] && { . /root/.nvm/nvm.sh; nvm use 20 >/dev/null; }`),
    i(`echo "[openhost] COMMIT_MSG=$(git log -1 --pretty=%s)"`),
    i(`echo "[openhost] AUTHOR=$(git log -1 --pretty=%an)"`),
    '',
    i(`# --- mode detection + standalone wrapping (mirrors local pipeline) ---`),
    i(`MODE=static`),
    i(`if [ -f next.config.js ] || [ -f next.config.mjs ]; then`),
    i(`  if grep -E "output[[:space:]]*:[[:space:]]*['\\"]export['\\"]" next.config.js next.config.mjs >/dev/null 2>&1; then`),
    i(`    echo "[openhost] Repo declares output=export → STATIC mode"`),
    i(`    MODE=static`),
    i(`  else`),
    i(`    MODE=ssr`),
    i(`    echo "[openhost] SSR mode → forcing output=standalone"`),
    i(`    if [ -f next.config.js ]; then`),
    i(`      mv next.config.js next.config.origin.js`),
    i(`      cat > next.config.js <<'EOCONFIG'`),
    i(`// generated by openhost — original preserved at next.config.origin.js`),
    i(`const orig = require("./next.config.origin.js");`),
    i(`const c = typeof orig === "function" ? orig() : orig;`),
    i(`module.exports = {`),
    i(`  ...c,`),
    i(`  output: "standalone",`),
    i(`  images: { ...(c.images || {}), unoptimized: true },`),
    i(`};`),
    i(`EOCONFIG`),
    i(`    else`),
    i(`      mv next.config.mjs next.config.origin.mjs`),
    i(`      cat > next.config.mjs <<'EOCONFIG'`),
    i(`// generated by openhost — original preserved at next.config.origin.mjs`),
    i(`import orig from "./next.config.origin.mjs";`),
    i(`const c = typeof orig === "function" ? await orig() : orig;`),
    i(`export default {`),
    i(`  ...c,`),
    i(`  output: "standalone",`),
    i(`  images: { ...(c.images || {}), unoptimized: true },`),
    i(`};`),
    i(`EOCONFIG`),
    i(`    fi`),
    i(`  fi`),
    i(`fi`),
    i(`echo "[openhost] MODE=$MODE"`),
    '',
    '  build:',
    '    commands:',
    '      - |',
    i(`set -euo pipefail`),
    i(`cd "$CODEBUILD_SRC_DIR"`),
    i(`[ -s /root/.nvm/nvm.sh ] && { . /root/.nvm/nvm.sh; nvm use 20 >/dev/null; }`),
    '',
    i(`# --- build script parity (ensureBuildScript) ---`),
    i(`if [ ! -f package.json ]; then`),
    i(`  echo "[openhost] No package.json — plain static site (out/ expected)"`),
    i(`  printf '%s\\n' '{"name":"openhost-site","private":true,"scripts":{"build":"echo static site; exit 0"}}' > package.json`),
    i(`fi`),
    i(`HAS_BUILD=$(node -e "const s=require('./package.json').scripts||{}; process.stdout.write(s.build?'yes':'no')")`),
    i(`if [ "$HAS_BUILD" = "no" ] && ! grep -q '"next"' package.json; then`),
    i(`  echo "[openhost] ERROR: package.json has no build script and no next dependency"`),
    i(`  exit 1`),
    i(`fi`),
    i(`if [ "$HAS_BUILD" = "no" ]; then`),
    i(`  echo "[openhost] No build script → injecting 'next build'"`),
    i(`  node -e "const fs=require('fs');const p=JSON.parse(fs.readFileSync('package.json'));p.scripts=Object.assign({},p.scripts,{build:'next build'});fs.writeFileSync('package.json',JSON.stringify(p,null,2))"`),
    i(`fi`),
    '',
    i(`# --- dependency install (lockfile-aware) ---`),
    i(`if [ -f pnpm-lock.yaml ]; then`),
    i(`  echo "[openhost] Installing dependencies with pnpm"`),
    i(`  corepack enable >/dev/null 2>&1 || npm i -g pnpm >/dev/null 2>&1`),
    i(`  pnpm install --frozen-lockfile`),
    i(`elif [ -f yarn.lock ]; then`),
    i(`  echo "[openhost] Installing dependencies with yarn"`),
    i(`  corepack enable >/dev/null 2>&1 || npm i -g yarn >/dev/null 2>&1`),
    i(`  yarn install --frozen-lockfile`),
    i(`elif [ -f package-lock.json ]; then`),
    i(`  echo "[openhost] Installing dependencies with npm ci"`),
    i(`  npm ci`),
    i(`else`),
    i(`  echo "[openhost] Installing dependencies with npm install (no lockfile)"`),
    i(`  npm install`),
    i(`fi`),
    '',
    i(`# --- compile ---`),
    i(`if [ "$MODE" = "ssr" ]; then`),
    i(`  echo "[openhost] Compiling Next.js (standalone output)"`),
    i(`  npx next build`),
    i(`else`),
    i(`  echo "[openhost] Running build"`),
    i(`  npm run build`),
    i(`  if [ ! -d out ]; then`),
    i(`    echo "[openhost] No out/ yet — attempting legacy next export"`),
    i(`    npx next export -o out 2>/dev/null || true`),
    i(`  fi`),
    i(`fi`),
    '',
    '  post_build:',
    '    commands:',
    '      - |',
    i(`set -euo pipefail`),
    i(`cd "$CODEBUILD_SRC_DIR"`),
    i(`[ -s /root/.nvm/nvm.sh ] && { . /root/.nvm/nvm.sh; nvm use 20 >/dev/null; }`),
    '',
    i(`if [ "$MODE" = "ssr" ]; then`),
    i(`  test -d .next/standalone || { echo "[openhost] ERROR: .next/standalone missing"; exit 1; }`),
    i(`  [ -d public ] && cp -r public/. .next/standalone/public || true`),
    i(`  cp -r .next/static/. .next/standalone/.next/static/`),
    i(`  mkdir -p pkg && cp -r .next/standalone/. pkg/`),
    i(`  cat > pkg/run.sh <<'EORUN'`),
    i(`#!/bin/bash`),
    i(`[ ! -d /tmp/cache ] && mkdir -p /tmp/cache`),
    i(`if [ ! -e .next/cache ]; then ln -s /tmp/cache .next/cache 2>/dev/null || true; fi`),
    i(`HOSTNAME=0.0.0.0 exec node server.js`),
    i(`EORUN`),
    i(`  chmod +x pkg/run.sh`),
    i(`  ( cd pkg && zip -qry ../bundle.zip . )`),
    i(`  SIZE_MB=$(( $(stat -c%s bundle.zip) / 1024 / 1024 ))`),
    i(`  echo "[openhost] Bundle size: \${SIZE_MB} MB"`),
    i(`  if [ "$SIZE_MB" -gt 50 ]; then echo "[openhost] ERROR: bundle exceeds 50 MB Lambda limit"; exit 1; fi`),
    i(`  aws s3 cp bundle.zip "s3://$BUCKET/versions/$CODEBUILD_RESOLVED_SOURCE_VERSION.zip" --no-progress`),
    i(`  echo "[openhost] Uploaded bundle → s3://$BUCKET/versions/$CODEBUILD_RESOLVED_SOURCE_VERSION.zip"`),
    i(`else`),
    i(`  [ -d out ] || { echo "[openhost] ERROR: no out/ directory produced"; exit 1; }`),
    i(`  aws s3 cp out/_next "s3://$BUCKET/static/_next" --recursive --no-progress --cache-control "public, max-age=31536000, immutable" 2>/dev/null || true`),
    i(`  aws s3 cp out/ "s3://$BUCKET/static/" --recursive --no-progress --exclude "_next/*" --cache-control "public, max-age=0, must-revalidate"`),
    i(`  echo "[openhost] Uploaded static assets → s3://$BUCKET/static/"`),
    i(`fi`),
    '',
  ].join('\n');

  /** Single 8-space indent helper (see indentation contract above). */
  function i(line: string): string {
    return '        ' + line;
  }
}
